        /// <summary>
        /// Возвращает статью бестиария по имени существа или его Id.
        /// Интеллектуально определяет подходящую запись с защитой от Null.
        /// </summary>
        public static BestiaryEntry GetEntryForCombatant(string? name, string? id = null, bool isPlayer = false, string? playerClass = null)
        {
            if (isPlayer)
            {
                string pClass = (playerClass ?? "Ветеран").ToLowerInvariant();
                if (pClass.Contains("маг") || pClass.Contains("mage"))
                    return Entries.First(e => e.Id == "hero_mage");
                if (pClass.Contains("наемник") || pClass.Contains("наёмник") || pClass.Contains("mercenary"))
                    return Entries.First(e => e.Id == "hero_mercenary");
                return Entries.First(e => e.Id == "hero_veteran");
            }

            string combined = $"{name} {id}".ToLowerInvariant();

            // Точные совпадения по боссам и уникальным врагам
            if (combined.Contains("углук") || combined.Contains("ugluk"))
                return Entries.First(e => e.Id == "orc_ugluk");
            if (combined.Contains("варг") || combined.Contains("varg") || combined.Contains("шаман"))
                return Entries.First(e => e.Id == "shaman_varg");
            if (combined.Contains("громгар") || combined.Contains("gromgar"))
                return Entries.First(e => e.Id == "boss_gromgar");
            if (combined.Contains("тень малкор") || combined.Contains("воплощение тьмы") || combined.Contains("malkor_shadow"))
                return Entries.First(e => e.Id == "boss_malkor_shadow");
            if (combined.Contains("малкор") || combined.Contains("malkor"))
                return Entries.First(e => e.Id == "boss_malkor");
            if (combined.Contains("ядро") || combined.Contains("core") || combined.Contains("титан") && combined.Contains("сердце"))
                return Entries.First(e => e.Id == "titan_core");
            if (combined.Contains("осколок") || combined.Contains("shard"))
                return Entries.First(e => e.Id == "heart_shard");
            if (combined.Contains("титан") || combined.Contains("titan"))
                return Entries.First(e => e.Id == "boss_titan");

            // Элита
            if (combined.Contains("тролль") || combined.Contains("troll"))
                return Entries.First(e => e.Id == "troll");
            if (combined.Contains("голем") || combined.Contains("golem"))
                return Entries.First(e => e.Id == "rune_golem");
            if (combined.Contains("инквизитор") || combined.Contains("inquisitor"))
                return Entries.First(e => e.Id == "shadow_inquisitor");
            if (combined.Contains("корол") || combined.Contains("king"))
                return Entries.First(e => e.Id == "shadow_king");

            // Рядовые и типы существ
            if (combined.Contains("щит") || combined.Contains("страж") || combined.Contains("shield"))
                return Entries.First(e => e.Id == "orc_shield");
            if (combined.Contains("разведчик") || combined.Contains("scout"))
                return Entries.First(e => e.Id == "orc_scout");
            if (combined.Contains("телохранитель") || combined.Contains("bodyguard") || combined.Contains("клык") || combined.Contains("гвардеец"))
                return Entries.First(e => e.Id == "orc_bodyguard");
            if (combined.Contains("лучник") || combined.Contains("archer"))
                return Entries.First(e => e.Id == "shadow_archer");
            if (combined.Contains("адепт") || combined.Contains("культист") || combined.Contains("adept"))
                return Entries.First(e => e.Id == "shadow_adept");
            if (combined.Contains("гончая") || combined.Contains("hound"))
                return Entries.First(e => e.Id == "void_hound");

            // Орк-рубака, орк-берсерк и дефолт
            return Entries.First(e => e.Id == "orc_berserker");
        }
